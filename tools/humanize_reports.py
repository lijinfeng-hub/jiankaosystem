def set_paragraph_text(paragraph, text: str) -> None:
    """Replace visible text while retaining the paragraph and first-run styling."""
    runs = paragraph.runs
    if not runs:
        paragraph.add_run(text)
        return
    runs[0].text = text
    for run in runs[1:]:
        run.text = ""


def set_cell_text(cell, text: str) -> None:
    paragraphs = cell.paragraphs
    if not paragraphs:
        cell.add_paragraph(text)
        return
    set_paragraph_text(paragraphs[0], text)
    for paragraph in paragraphs[1:]:
        set_paragraph_text(paragraph, "")


def replace_paragraphs(doc: Document, replacements: Dict[str, str]) -> None:
    for paragraph in doc.paragraphs:
        if paragraph.text in replacements:
            set_paragraph_text(paragraph, replacements[paragraph.text])


def replace_table_cells(doc: Document, replacements: Dict[Tuple[int, int, int], str]) -> None:
    for (table_index, row_index, col_index), text in replacements.items():
        set_cell_text(doc.tables[table_index].rows[row_index].cells[col_index], text)


def fix_manual_checklist_bullet(doc: Document) -> None:
    """Let the existing List Bullet style render the final checklist item."""
    target = "已导出 CSV，并将方案编号、导出文件和日志一起归档。"
    for paragraph in doc.paragraphs:
        if paragraph.text != target or paragraph._p.pPr is None:
            continue
        num_pr = paragraph._p.pPr.find(qn("w:numPr"))
        if num_pr is not None:
            paragraph._p.pPr.remove(num_pr)


