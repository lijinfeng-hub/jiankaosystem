def process(input_path: str, output_path: str, paragraph_map: Dict[str, str], table_map: Dict[Tuple[int, int, int], str]) -> None:
    doc = Document(input_path)
    before = [p.text for p in doc.paragraphs]
    replace_paragraphs(doc, paragraph_map)
    replace_table_cells(doc, table_map)
    if "用户操作手册" in output_path:
        fix_manual_checklist_bullet(doc)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    doc.save(output_path)
    after = [p.text for p in doc.paragraphs]
    changed = sum(a != b for a, b in zip(before, after))
    print(f"{output_path}: changed_paragraphs={changed}, table_edits={len(table_map)}")


